"""Generates src/pidgely/resources/_async.py from _sync.py.

python scripts/generate_async.py          # write the file
python scripts/generate_async.py --check  # fail when it is out of date (CI)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "src" / "pidgely" / "resources"
CLASSES = [
    "EmailAttachments",
    "Emails",
    "Batch",
    "Domains",
    "ApiKeys",
    "ContactSegments",
    "Contacts",
    "Segments",
    "Broadcasts",
    "Templates",
    "Webhooks",
    "SuppressionsBatch",
    "Suppressions",
]


def generate(source: str) -> str:
    out = source.replace(
        '"""Synchronous resources. ``_async.py`` is generated from this file by\n``scripts/generate_async.py``: edit this file, then run the script."""',
        '"""Asynchronous resources. GENERATED by scripts/generate_async.py from _sync.py: do not edit."""',
    )
    out = out.replace("from .._client import Pidgely as _Client", "from .._client import AsyncPidgely as _Client")
    # Class names (definitions, instantiations, annotations, __all__), but not the
    # Resend-style property names such as `def Batch(self)` / `def Segments(self)`.
    for name in CLASSES:
        out = re.sub(rf'(?<![\w.])(?<!def ){name}(?=[(:\]",])', f"Async{name}", out)
        out = re.sub(rf'"{name}"', f'"Async{name}"', out)
    lines = out.split("\n")
    result = []
    for i, line in enumerate(lines):
        prev = lines[i - 1].strip() if i else ""
        m = re.match(r"^(    )def (?!_)(\w+)\(self", line)
        if m and prev != "@property":
            line = line.replace("    def ", "    async def ", 1)
        line = line.replace("self._client._request(", "await self._client._request(")
        line = re.sub(r"return self\.(\w+)\(", r"return await self.\1(", line)
        result.append(line)
    return "\n".join(result)


def main() -> int:
    source = (ROOT / "_sync.py").read_text()
    target = ROOT / "_async.py"
    generated = generate(source)
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != generated:
            print("src/pidgely/resources/_async.py is out of date: run python scripts/generate_async.py")
            return 1
        return 0
    target.write_text(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
